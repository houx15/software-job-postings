    def balance(S, firms, qs):
        idx = pd.MultiIndex.from_product([sorted(firms), ["early", "exp"], qs], names=["rcid", "sg", "q"])
        g = S.reindex(idx, fill_value=0).reset_index(); g["ly"] = np.log1p(g.iloc[:, 3].astype(float)); g["early"] = (g.sg == "early").astype(int)
        g["A"] = g.rcid.isin(ad).astype(int); return g
    qs = [str(q) for q in pd.period_range("2021Q1", fe.LAST_FULL_Q, freq="Q")]
    firms = (us - pre_ad) & set(P.index.get_level_values(0).astype("int64"))
    g = balance(P, firms, qs)
    evs["postings (P2), 2021Q1-2026Q2"] = firm_did(g, "Postings (P2), 2021Q1-2026Q2")
