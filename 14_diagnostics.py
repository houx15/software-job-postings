def zexpo(col="eloundou_beta_gpt4"):
    e = EXPO[col].dropna(); return (e - e.mean()) / e.std()
def q_of(month): return str(pd.Period(month, "M").asfreq("Q"))

def ev_summary(lab, g, fe_=FE_MAIN):
    t, b, V, npre, F, p = fe.event(g, fe=fe_)
    out(f"- EVENT {lab}: pre-trend Wald chi2({npre}) = {F:.1f}, p = {p:.2g}; leads " +
        ", ".join(f"{q} {x:+.3f}" for q, x in zip(t.q[:npre], t.b[:npre])) +
        f"; post 2023Q1 {t.set_index('q').b.get('2023Q1', np.nan):+.3f}, 2025Q3 {t.set_index('q').b.get('2025Q3', np.nan):+.3f}, last {t.q.iloc[-1]} {t.b.iloc[-1]:+.3f} ({t.se.iloc[-1]:.3f})")
    return t

# ------------------------------------------------------------------ 1. power
def power():
    z = zexpo()
    g = fe.cells()
    pre = g[g.q <= fe.PRE_END].groupby("soc6", observed=True).n.sum()
    occ = pd.DataFrame({"w": pre}).join(z.rename("E"), how="inner")
    occ = occ.sort_values("E"); cw = occ.w.cumsum() / occ.w.sum(); occ["quint"] = np.minimum((cw * 5).clip(upper=4.999).astype(int) + 1, 5)
    m = occ.groupby("quint").apply(lambda x: np.average(x.E, weights=x.w))
    gap = m[5] - m[1]
    out("## 1. Power / minimum detectable effect\n")
    out(f"Exposure gap, top vs bottom quintile of occupations (weighted by pre-period postings in the firm sample): {gap:.2f} SD of E.")
    lit = {"Brynjolfsson-Chandar-Chen (ADP, 22-25 in top vs bottom exposure quintile, ~2.5 yrs)": np.log(1 - 0.13),
           "Hosseini Maasoum-Lichtinger (Revelio profiles, junior in adopters vs non, 6 quarters)": np.log(1 - 0.077),
           "Hosseini Maasoum-Lichtinger, triple diff (~10% after 6 quarters)": np.log(1 - 0.10)}
    out("\n| Literature effect | log points | per SD of E (if spread over the quintile gap) |\n|---|---|---|")
    for k, v in lit.items(): out(f"| {k} | {v:.3f} | {v / gap:.3f} |")
    se = {"Occupation-level, US LinkedIn-only (10_designA)": 0.017, "Firm-level, firm FE (13)": 0.037,
          "Firm-level, firm x seniority x quarter FE": 0.033, "Firm-level, LinkedIn-only": 0.023}
    out("\n| Design | SE of Early x E x Post | MDE (80% power, 5% two-sided) = 2.80 SE |\n|---|---|---|")
    for k, v in se.items(): out(f"| {k} | {v:.3f} | {2.8 * v:.3f} |")
    # honest-DiD based detectable effect: half-width of the robust CI (main spec)
    out("\nHonest-DiD (main firm spec): half-width of the 95% robust interval = smallest effect that could be declared nonzero:\n")
    out("| target | original | SD M=0 | SD M=0.25*max curvature | RM Mbar=0.25 | RM Mbar=1 |\n|---|---|---|---|---|---|")
    sd = pd.read_csv(os.path.join(HERE, "data", "firmFE", "hd_main_sd.csv")); rm = pd.read_csv(os.path.join(HERE, "data", "firmFE", "hd_main_rm.csv"))
    for tg in fe.TARGETS:
        s = sd[sd.target == tg]; r = rm[rm.target == tg]; hw = lambda x: (x.ub - x.lb).iloc[0] / 2
        Ms = sorted(s[s.restriction == "SD"].M.unique())
        out(f"| {tg} | {hw(s[s.restriction=='original']):.3f} | {hw(s[(s.restriction=='SD') & (s.M==Ms[0])]):.3f} | "
            f"{hw(s[(s.restriction=='SD') & (s.M==Ms[1])]):.3f} | {hw(r[r.Mbar==0.25]):.3f} | {hw(r[r.Mbar==1.0]):.3f} |")
    # pre-trend slope vs literature-implied slope
    t = pd.read_csv(os.path.join(HERE, "data", "firmFE", "event_US_all_sources_firm_FE.csv"))
    pre = t[t.q < REF]; k = np.arange(-len(pre), 0)
    slope = np.polyfit(np.append(k, 0), np.append(pre.b, 0), 1)[0]
    bcc_q = (lit[list(lit)[0]] / gap) / 10
    out(f"\nPre-trend: OLS slope of event coefficients 2021Q1..2022Q3 = {slope:+.4f} log points per SD per quarter "
        f"(the leads fall by {pre.b.iloc[0]:.3f} over {len(pre)} quarters). BCC-implied effect per SD per quarter (13% over ~10 quarters) = {bcc_q:+.4f}. "
        f"Ratio |pre-trend| / |BCC slope| = {abs(slope / bcc_q):.1f}.")
    # residual noise of the event coefficients around a smooth path
    post = t[t.q > REF]
    out(f"Median SE of post-period event coefficients: {post.se.median():.3f}; max {post.se.max():.3f} (2023Q2-Q3 spike quarters).")
    write("power")

