def firm_did(g, lab, yvar="ly", event_ref="2022Q4"):
    """g: rcid x sg x q with adopter flag A. HL-style: (i) DiD adopter x post for juniors and seniors separately,
    (ii) triple diff A x Early x Post | firm^q + firm^sg + sg^q, SE clustered by firm."""
    g = g.copy(); g["post"] = (g.q >= POST1).astype(int)
    r = {}
    for s in ["early", "exp"]:
        h = g[g.sg == s].copy(); h["D"] = h.A * h.post
        r[s] = pf.feols(f"{yvar} ~ D | rcid + q", data=h, vcov={"CRV1": "rcid"}).tidy().loc["D"]
    g["T"] = g.A * g.early * g.post
    r["triple"] = pf.feols(f"{yvar} ~ T | rcid^q + rcid^sg + sg^q", data=g, vcov={"CRV1": "rcid"}).tidy().loc["T"]
    st = lambda x: f"{x['Estimate']:+.3f}{fe.star(x['Pr(>|t|)'])} ({x['Std. Error']:.3f})"
    out(f"| {lab} | {st(r['early'])} | {st(r['exp'])} | {st(r['triple'])} |")
    # event study of the triple diff
    qs = sorted(g.q.unique()); names = []
    for q in qs:
        if q == event_ref: continue
        nm = "k_" + q; g[nm] = g.A * g.early * (g.q == q); names.append(nm)
    m = pf.feols(f"{yvar} ~ " + " + ".join(names) + " | rcid^q + rcid^sg + sg^q", data=g, vcov={"CRV1": "rcid"})
    t = m.tidy(); t = pd.DataFrame({"q": [n[2:] for n in names], "b": t.loc[names, "Estimate"].values, "se": t.loc[names, "Std. Error"].values})
    leads = [i for i, n in enumerate(names) if n[2:] < event_ref and n[2:] >= "2021Q1"]
    R = np.zeros((len(leads), len(names)))
    for i, j in enumerate(leads): R[i, j] = 1
    w = m.wald_test(R=R)
    return t, float(w["statistic"]), float(w["pvalue"]), len(leads)

