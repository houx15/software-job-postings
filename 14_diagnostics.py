def hires():
    out("## 5. Outcome = hires (individual_positions), occupation level\n")
    h = pd.read_parquet(os.path.join(HERE, "data", "hires", "occ.parquet"))
    h = h[h.seniority.between(1, 4) & h.soc6.notna()].copy(); h["q"] = h.month.map(q_of); h["w"] = h.w.astype(float)
    tot = h.groupby("q").w.sum()
    out("Weighted hires per quarter (all US, seniority 1-4) — profile lag shows as a fall in recent quarters: " +
        ", ".join(f"{q}: {v/1e6:.2f}M" for q, v in tot.items() if q[-2:] in ("Q1",) or q >= "2025Q1"))
    z = zexpo(); h = h[h.soc6.isin(z.index)]
    last = os.environ.get("HIRES_LAST_Q", "2025Q4")
    def occ_cells(x, early_def):
        x = x[(x.q >= "2019Q1") & (x.q <= last)].copy(); x["sg"] = np.where(early_def(x), "early", "exp")
        g = x.groupby(["soc6", "sg", "q"]).w.sum()
        idx = pd.MultiIndex.from_product([g.index.levels[0], ["early", "exp"], sorted(x.q.unique())], names=["soc6", "sg", "q"])
        g = g.reindex(idx, fill_value=0).reset_index()
        pre = g[g.q <= fe.PRE_END].groupby(["soc6", "sg"]).w.sum().unstack()
        keep = pre[pre.min(axis=1) >= 200].index; g = g[g.soc6.isin(keep)].copy()
        g["ly"] = np.log1p(g.w); g["early"] = (g.sg == "early").astype(int); g["E"] = g.soc6.map(z)
        g["post"] = (g.q >= POST1).astype(int); g["post2"] = (g.q >= POST2).astype(int); g["os"] = g.soc6 + g.sg
        g["T1"] = g.early * g.E * g.post; g["T2"] = g.early * g.E * g.post2
        return g
    specs = [("Hires, early = seniority 1-2", h, lambda x: x.seniority <= 2),
             ("First-job hires vs other hires (canaries proxy)", h, lambda x: x.first_job.astype(bool))]
    out(f"\nTriple diff, soc6 x group x quarter, 2019Q1-{last}, FE soc6^q + sg^q + soc6^sg, SE by occupation, outcome log(1+weighted hires):\n")
    out("| Specification | occupations | Post | Post2 | YoY Post | pre-trend chi2 (2019Q1-2022Q2 leads, ref 2022Q3) | p |\n|---|---|---|---|---|---|---|")
    evs = {}
    for lab, x, fn in specs:
        g = occ_cells(x, fn)
        t = pf.feols("ly ~ T1 + T2 | soc6^q + sg^q + os", data=g, vcov={"CRV1": "soc6"}).tidy()
        gy = g.sort_values(["soc6", "sg", "q"]).copy(); gy["ly"] = gy.ly - gy.groupby(["soc6", "sg"]).ly.shift(4); gy = gy[gy.ly.notna()]
        ty = pf.feols("ly ~ T1 + T2 | soc6^q + sg^q + os", data=gy, vcov={"CRV1": "soc6"}).tidy()
        qs = sorted(g.q.unique()); names = []
        for q in qs:
            if q == REF: continue
            nm = "k_" + q; g[nm] = g.early * g.E * (g.q == q); names.append(nm)
        m = pf.feols("ly ~ " + " + ".join(names) + " | soc6^q + sg^q + os", data=g, vcov={"CRV1": "soc6"})
        tt = m.tidy(); ev = pd.DataFrame({"q": [n[2:] for n in names], "b": tt.loc[names, "Estimate"].values, "se": tt.loc[names, "Std. Error"].values})
        leads = [i for i, n in enumerate(names) if n[2:] < REF]; R = np.zeros((len(leads), len(names)))
        for i, j in enumerate(leads): R[i, j] = 1
        w = m.wald_test(R=R); evs[lab] = ev
        if lab.startswith("Hires, early"):   # Rambachan-Roth on the hires event study (same runner as 13)
            V = pd.DataFrame(m._vcov, index=m._coefnames, columns=m._coefnames).loc[names, names].to_numpy()
            bb = ev.b.to_numpy(); npre = len(leads); post_q = list(ev.q[npre:]); npost = len(post_q)
            la = np.array([1.0 if q >= POST1 else 0.0 for q in post_q]); la /= la.sum()
            l1 = np.array([1.0 if q == "2024Q1" else 0.0 for q in post_q])
            lz = np.array([1.0 if "2025Q1" <= q <= "2025Q3" else 0.0 for q in post_q]); lz /= lz.sum()
            Mmax = float(np.abs(np.diff(np.concatenate([bb[:npre], [0.0]]), n=2)).max())
            hd_dir = os.path.join(HERE, "data", "diag"); os.makedirs(hd_dir, exist_ok=True); npz = os.path.join(hd_dir, "hd_hires.npz")
            np.savez(npz, beta=bb, sigma=V, npre=npre, npost=npost, lvecs=np.vstack([l1, la, lz]),
                     lnames=np.array(["2024Q1", f"avg 2023Q1-{last}", "avg 2025Q1-2025Q3"]),
                     Mvec=np.array([0.0] + [round(f * Mmax, 5) for f in (0.5, 1.0, 2.0)]), Mbarvec=np.array([0.5, 1.0, 2.0]))
            import subprocess
            r_ = subprocess.run([fe.HD_PY, os.path.join(HERE, "tools", "honest_bounds.py"), npz, os.path.join(hd_dir, "hd_hires")], capture_output=True, text=True)
            hd_note = f"HonestDiD on hires (early = seniority 1-2): exit {r_.returncode}; max |2nd diff| of leads = {Mmax:.4f}"
        out(f"| {lab} | {g.soc6.nunique()} | {fe.fmt(t,'T1')} | {fe.fmt(t,'T2')} | {fe.fmt(ty,'T1')} | {float(w['statistic']):.1f} | {float(w['pvalue']):.2g} |")
    out("")
    hp = os.path.join(HERE, "data", "diag")
    if os.path.exists(os.path.join(hp, "hd_hires_sd.csv")):
        out(hd_note + "\n\n| target | restriction | M / Mbar | lb | ub |\n|---|---|---|---|---|")
        for suf in ["_sd.csv", "_rm.csv"]:
            x = pd.read_csv(os.path.join(hp, "hd_hires" + suf))
            for _, z_ in x.iterrows():
                mm = z_["M"] if "M" in x else z_["Mbar"]
                out(f"| {z_.target} | {z_.restriction} | {'' if pd.isna(mm) else f'{mm:.4g}'} | {z_.lb:.3f} | {z_.ub:.3f} |")
        out("")
    for lab, ev in evs.items():
        out(f"- EVENT {lab}: " + ", ".join(f"{q} {b:+.3f} ({s:.3f})" for q, b, s in zip(ev.q, ev.b, ev.se) if q[-2:] == "Q1" or q in ("2022Q2", "2022Q4")))
    # descriptive: software developers (15-1252) first-job hires vs other, index 2022Q3=100; and early share
    fig, axs = plt.subplots(1, 2, figsize=(13, 4.3))
    sw = h[h.soc6 == "15-1252"]; x = sw.groupby(["q", "first_job"]).w.sum().unstack(); x = x[(x.index >= "2019Q1") & (x.index <= last)]
    (100 * x / x.loc[REF]).rename(columns={True: "first job", False: "other hires"}).plot(ax=axs[0], marker="o", ms=3)
    y = sw[sw.q.between("2019Q1", last)]; e = y[y.seniority <= 2].groupby("q").w.sum() / y.groupby("q").w.sum()
    ax2 = axs[0].twinx(); ax2.plot(range(len(e)), e.values, color="gray", ls="--", label="early (1-2) share, right"); ax2.legend(fontsize=7, loc="lower left")
    axs[0].set_title("US software developers (15-1252): weighted hires, 2022Q3 = 100", fontsize=9); axs[0].tick_params(axis="x", rotation=60, labelsize=7)
    for lab, ev in evs.items():
        ev = pd.concat([ev, pd.DataFrame({"q": [REF], "b": [0.0], "se": [0.0]})]).sort_values("q")
        axs[1].errorbar(np.arange(len(ev)), ev.b, yerr=1.96 * ev.se, fmt="o-", ms=3, capsize=2, label=lab)
    axs[1].set_xticks(np.arange(len(ev))[::2]); axs[1].set_xticklabels(list(ev.q)[::2], rotation=60, fontsize=7); axs[1].axhline(0, color="k", lw=.6)
    axs[1].axvline(list(ev.q).index(REF), color="gray", ls=":"); axs[1].legend(fontsize=7)
    axs[1].set_title("Hires: Early x E x quarter (occupation level), ref 2022Q3", fontsize=9)
    fig.tight_layout(); fig.savefig(os.path.join(FIG, "diag_hires_1.png"), dpi=150); plt.close(fig)
    write("hires")

